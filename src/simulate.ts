// Steady-state traffic model: push every client's requests through the design and work out,
// for each component, how much load it gets, how busy it is and how slow that makes it.
//
// It is deliberately simple (averages, no randomness) so every number can be checked by hand:
//
// * Traffic is a pair of rates, reads and writes, in requests per second.
// * Connection labels filter it: "reads" carries only reads, "writes" only writes.
// * Each kind moves traffic in one of four ways (see `behaviorOf`).
// * Capacity = capacity per replica × replicas (× shards). SQL replicas only serve reads:
//   every write still goes to the primary.
// * Queueing: a component at utilization ρ answers in latency / (1 − ρ), the M/M/1 result.
//   Latency doubles at 50% busy, is 10× at 90%, and explodes as ρ approaches 1.
// * Past 100% a component serves only what it can. The rest is dropped, or piles up as a
//   backlog when a queue feeds it, and only the served part flows downstream.
// * A failed (down) component serves nothing. Load balancers and queues health-check their
//   targets and send everything to the ones still up; other routers have no such fallback.

import type { ComponentKind } from './catalog'
import type { Design, DesignEdge, DesignNode } from './design'

export interface Traffic {
  reads: number
  writes: number
}

/**
 * - `split`: route each request to ONE downstream (load balancer, gateway, queue consumers).
 * - `fanout`: every request calls EVERY downstream (an application server, a pub/sub stream).
 * - `cache`: answer the hit-rate share of reads, pass misses and writes on.
 * - `store`: answer everything, pass only writes on (replication, indexing).
 */
export type Behavior = 'split' | 'fanout' | 'cache' | 'store'

export interface NodeStats {
  id: string
  /** Switched off by failure injection: everything that reaches it is lost. */
  failed: boolean
  /** Traffic arriving (offered load). */
  load: Traffic
  /** Traffic actually handled: the load, scaled down when overloaded. */
  served: Traffic
  capacity: Traffic
  /** Fraction of capacity in use; above 1 means overloaded. */
  utilization: number
  overloaded: boolean
  /** Requests per second turned away. */
  dropped: number
  /** Requests per second piling up in the queue in front of this component. */
  backlog: number
  /** Reads answered from cache (cache and CDN only). */
  absorbed: number
  /** Own latency including queueing delay, in ms. */
  latency: number
  /** Average time to answer one request, including synchronous downstream calls, in ms. */
  responseTime: number
}

export interface EdgeStats {
  id: string
  traffic: Traffic
  /** Not on the caller's critical path (labelled async/events, or leaving a queue/stream). */
  async: boolean
  /** Closes a loop, so the simulation ignores it. */
  ignored: boolean
}

export interface SimulationResult {
  nodes: Record<string, NodeStats>
  edges: Record<string, EdgeStats>
  /** Requests per second generated by all clients. */
  totalRps: number
  /** Client-request-weighted average response time, in ms. */
  responseTime: number
  /** Busiest component (highest utilization), if anything gets traffic. */
  bottleneck: string | null
  overloaded: string[]
  droppedRps: number
  backlogRps: number
  warnings: string[]
}

/** Queueing delay is computed at no more than 99% busy, i.e. at most 100× the base latency. */
export const MAX_QUEUEING_UTILIZATION = 0.99

const ZERO: Traffic = { reads: 0, writes: 0 }
export const totalOf = (t: Traffic) => t.reads + t.writes
const add = (a: Traffic, b: Traffic): Traffic => ({ reads: a.reads + b.reads, writes: a.writes + b.writes })
const scale = (t: Traffic, k: number): Traffic => ({ reads: t.reads * k, writes: t.writes * k })

export function behaviorOf(kind: ComponentKind): Behavior {
  switch (kind) {
    case 'client':
    case 'dns':
    case 'load-balancer':
    case 'api-gateway':
    case 'queue':
      return 'split'
    case 'cdn':
    case 'cache':
      return 'cache'
    case 'sql-db':
    case 'nosql-db':
    case 'object-storage':
    case 'search':
      return 'store'
    case 'service':
    case 'worker':
    case 'stream':
    case 'external-api':
      return 'fanout'
  }
}

/** Which kinds of request a connection carries, from its label. */
export function edgeCarries(edge: DesignEdge): { reads: boolean; writes: boolean } {
  const label = edge.label?.trim().toLowerCase()
  if (label === 'reads' || label === 'read') return { reads: true, writes: false }
  if (label === 'writes' || label === 'write') return { reads: false, writes: true }
  return { reads: true, writes: true }
}

export function isAsyncEdge(design: Design, edge: DesignEdge): boolean {
  const label = edge.label?.trim().toLowerCase()
  if (label === 'async' || label === 'events') return true
  const source = design.nodes.find((n) => n.id === edge.from)
  return source?.kind === 'queue' || source?.kind === 'stream'
}

/** Requests per second the component can serve, separately for reads and writes. */
export function capacityOf(node: DesignNode): Traffic {
  const perReplica = node.params.capacity
  if (perReplica === undefined) return { reads: Infinity, writes: Infinity }
  const replicas = node.params.replicas ?? 1
  const shards = node.params.shards ?? 1
  if (node.kind === 'sql-db') {
    // Read replicas spread reads; writes all land on the primary of each shard.
    return { reads: perReplica * replicas * shards, writes: perReplica * shards }
  }
  return { reads: perReplica * replicas * shards, writes: perReplica * replicas * shards }
}

export function utilizationOf(load: Traffic, capacity: Traffic): number {
  return load.reads / capacity.reads + load.writes / capacity.writes
}

/** M/M/1 response time: base / (1 − ρ), with ρ capped so overload stays finite. */
export function queueingLatency(base: number, utilization: number): number {
  return base / (1 - Math.min(utilization, MAX_QUEUEING_UTILIZATION))
}

export interface SimulateOptions {
  /**
   * Pretend every component has infinite capacity, so nothing is capped. Utilizations then
   * scale exactly with traffic, which is what `breakingPoint` needs.
   */
  unlimitedCapacity?: boolean
  /** Components that are down. */
  failed?: ReadonlySet<string>
}

export function simulate(design: Design, options: SimulateOptions = {}): SimulationResult {
  const warnings: string[] = []
  const failed = options.failed ?? new Set<string>()
  const byId = new Map(design.nodes.map((n) => [n.id, n]))
  const name = (id: string) => byId.get(id)?.label ?? id

  // 1. Loops would make traffic circulate forever, so drop the edges that close them.
  const ignored = findLoopEdges(design)
  for (const id of ignored) {
    const edge = design.edges.find((e) => e.id === id)!
    warnings.push(`${name(edge.from)} → ${name(edge.to)} closes a loop, so the simulation ignores it`)
  }
  const live = design.edges.filter((e) => !ignored.has(e.id))
  const outs = new Map<string, DesignEdge[]>(design.nodes.map((n) => [n.id, []]))
  const ins = new Map<string, DesignEdge[]>(design.nodes.map((n) => [n.id, []]))
  for (const edge of live) {
    outs.get(edge.from)!.push(edge)
    ins.get(edge.to)!.push(edge)
  }
  const order = topologicalOrder(design, live)

  // 2. Push traffic downstream in topological order, so each node's load is final when visited.
  const offered = new Map<string, Traffic>(design.nodes.map((n) => [n.id, ZERO]))
  const edgeTraffic = new Map<string, Traffic>(design.edges.map((e) => [e.id, ZERO]))
  const nodes: Record<string, NodeStats> = {}
  let totalRps = 0

  for (const node of design.nodes) {
    if (node.kind !== 'client') continue
    const rps = node.params.rps
    const reads = rps * (node.params.readRatio / 100)
    offered.set(node.id, { reads, writes: rps - reads })
    totalRps += rps
  }

  for (const id of order) {
    const node = byId.get(id)!
    const load = offered.get(id)!
    const down = failed.has(id)
    const capacity = capacityOf(node)
    const utilization = down ? 0 : utilizationOf(load, capacity)
    const served = down ? ZERO : utilization > 1 && !options.unlimitedCapacity ? scale(load, 1 / utilization) : load
    const lost = totalOf(load) - totalOf(served)
    const feeders = ins.get(id)!
    const fedByQueue =
      feeders.length > 0 && feeders.every((e) => ['queue', 'stream'].includes(byId.get(e.from)!.kind))

    const behavior = behaviorOf(node.kind)
    const hitRate = behavior === 'cache' ? node.params.hitRate / 100 : 0
    const absorbed = served.reads * hitRate
    const passOn: Traffic =
      behavior === 'cache'
        ? { reads: served.reads - absorbed, writes: served.writes }
        : behavior === 'store'
          ? { reads: 0, writes: served.writes }
          : served

    // Load balancers and queues skip dead targets (unless every target is dead).
    const healthAware = node.kind === 'load-balancer' || node.kind === 'queue'
    const isUp = (edge: DesignEdge) => !healthAware || !failed.has(edge.to)
    for (const [edge, traffic] of route(behavior, passOn, outs.get(id)!, isUp)) {
      edgeTraffic.set(edge.id, traffic)
      offered.set(edge.to, add(offered.get(edge.to)!, traffic))
    }

    nodes[id] = {
      id,
      failed: down,
      load,
      served,
      capacity,
      utilization,
      overloaded: utilization > 1,
      dropped: fedByQueue ? 0 : lost,
      backlog: fedByQueue ? lost : 0,
      absorbed,
      latency: down ? 0 : queueingLatency(node.params.latency ?? 0, utilization),
      responseTime: 0,
    }
  }

  // 3. Response times bottom-up: own latency plus the synchronous calls an average request makes.
  for (const id of [...order].reverse()) {
    const stats = nodes[id]
    const handled = totalOf(stats.served)
    let downstream = 0
    if (handled > 0) {
      for (const edge of outs.get(id)!) {
        if (isAsyncEdge(design, edge)) continue
        downstream += (totalOf(edgeTraffic.get(edge.id)!) / handled) * nodes[edge.to].responseTime
      }
    }
    stats.responseTime = stats.latency + downstream
  }

  const edges: Record<string, EdgeStats> = {}
  for (const edge of design.edges) {
    edges[edge.id] = {
      id: edge.id,
      traffic: edgeTraffic.get(edge.id)!,
      async: isAsyncEdge(design, edge),
      ignored: ignored.has(edge.id),
    }
  }

  // 4. Summary.
  const clients = design.nodes.filter((n) => n.kind === 'client')
  if (clients.length === 0) warnings.push('Add a client: without one there is no traffic to simulate')
  const responseTime =
    totalRps > 0 ? clients.reduce((sum, c) => sum + c.params.rps * nodes[c.id].responseTime, 0) / totalRps : 0

  let bottleneck: string | null = null
  for (const node of design.nodes) {
    const stats = nodes[node.id]
    if (node.kind === 'client') continue
    if (stats.failed) continue
    if (totalOf(stats.load) === 0) {
      if (clients.length > 0) warnings.push(`${node.label} receives no traffic`)
      continue
    }
    if (!bottleneck || stats.utilization > nodes[bottleneck].utilization) bottleneck = node.id
  }
  const all = Object.values(nodes)

  return {
    nodes,
    edges,
    totalRps,
    responseTime,
    bottleneck,
    overloaded: design.nodes.filter((n) => nodes[n.id].overloaded).map((n) => n.id),
    droppedRps: all.reduce((sum, s) => sum + s.dropped, 0),
    backlogRps: all.reduce((sum, s) => sum + s.backlog, 0),
    warnings,
  }
}

/** The same design with every client sending `factor` times as many requests. */
export function scaleTraffic(design: Design, factor: number): Design {
  return {
    ...design,
    nodes: design.nodes.map((node) =>
      node.kind === 'client' ? { ...node, params: { ...node.params, rps: node.params.rps * factor } } : node,
    ),
  }
}

/**
 * How much more traffic the design takes before its first component hits 100%, and which one.
 * Every rule in the model is linear in traffic until something saturates, so this is exact:
 * simulate with no capacity limits and divide by the highest utilization.
 */
export function breakingPoint(design: Design): { factor: number; nodeId: string } | null {
  const sim = simulate(design, { unlimitedCapacity: true })
  let worst: NodeStats | null = null
  for (const stats of Object.values(sim.nodes)) {
    if (stats.utilization > 0 && (!worst || stats.utilization > worst.utilization)) worst = stats
  }
  return worst ? { factor: 1 / worst.utilization, nodeId: worst.id } : null
}

/**
 * Traffic each outgoing edge receives, honouring read/write labels. A split only uses edges
 * that pass `usable` (healthy targets), falling back to all of them if none do.
 */
function route(
  behavior: Behavior,
  traffic: Traffic,
  edges: DesignEdge[],
  usable: (edge: DesignEdge) => boolean,
): [DesignEdge, Traffic][] {
  if (behavior !== 'split') {
    return edges.map((edge) => {
      const carries = edgeCarries(edge)
      return [edge, { reads: carries.reads ? traffic.reads : 0, writes: carries.writes ? traffic.writes : 0 }]
    })
  }
  // Split each kind of request evenly between the (healthy) edges that accept it.
  const healthy = edges.filter(usable)
  const targets = healthy.length > 0 ? new Set(healthy) : new Set(edges)
  const readers = edges.filter((e) => targets.has(e) && edgeCarries(e).reads).length
  const writers = edges.filter((e) => targets.has(e) && edgeCarries(e).writes).length
  return edges.map((edge) => {
    const carries = edgeCarries(edge)
    const open = targets.has(edge)
    return [
      edge,
      {
        reads: open && carries.reads ? traffic.reads / readers : 0,
        writes: open && carries.writes ? traffic.writes / writers : 0,
      },
    ]
  })
}

/**
 * Depth-first search starting from clients (so loops are cut where they turn back towards
 * the users, not somewhere arbitrary). An edge into a node still on the stack closes a loop.
 */
function findLoopEdges(design: Design): Set<string> {
  const state = new Map<string, 'active' | 'done'>()
  const loopEdges = new Set<string>()
  const visit = (id: string) => {
    state.set(id, 'active')
    for (const edge of design.edges) {
      if (edge.from !== id) continue
      const next = state.get(edge.to)
      if (next === 'active') loopEdges.add(edge.id)
      else if (next === undefined) visit(edge.to)
    }
    state.set(id, 'done')
  }
  const starts = [...design.nodes].sort((a, b) => Number(b.kind === 'client') - Number(a.kind === 'client'))
  for (const node of starts) if (!state.has(node.id)) visit(node.id)
  return loopEdges
}

/** Kahn's algorithm over the loop-free edges, keeping design order among ready nodes. */
function topologicalOrder(design: Design, edges: DesignEdge[]): string[] {
  const indegree = new Map(design.nodes.map((n) => [n.id, 0]))
  for (const edge of edges) indegree.set(edge.to, indegree.get(edge.to)! + 1)
  const ready = design.nodes.filter((n) => indegree.get(n.id) === 0).map((n) => n.id)
  const order: string[] = []
  while (ready.length > 0) {
    const id = ready.shift()!
    order.push(id)
    for (const edge of edges) {
      if (edge.from !== id) continue
      const left = indegree.get(edge.to)! - 1
      indegree.set(edge.to, left)
      if (left === 0) ready.push(edge.to)
    }
  }
  return order
}
